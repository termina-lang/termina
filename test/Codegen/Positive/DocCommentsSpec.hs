{-# LANGUAGE OverloadedStrings #-}
-- | The documentation comments of a module in its C files, as
-- @termina deliver --docs@ writes them.
module Codegen.Positive.DocCommentsSpec (spec) where

import qualified Data.Text as T

import Pipeline.Common (renderDocumentedFiles)

import Test.Hspec

-- | A struct with its fields, and a function with its parameters, one of
-- them only written.
pointAndDistance :: String
pointAndDistance = unlines
  [ "/**"
  , " * A point of the screen."
  , " */"
  , "struct Point {"
  , "    x : u32; /**< Abscissa, in pixels. */"
  , "    y : u32; /**< Ordinate, in pixels. */"
  , "};"
  , ""
  , "/**"
  , " * Distance between two points along the axes."
  , " *"
  , " * @param a First point."
  , " * @param b Second point."
  , " * @param[out] d The distance, in pixels."
  , " */"
  , "function manhattan(a : Point, b : Point, d : &mut u32) {"
  , "    *d = a.x + b.x + a.y + b.y;"
  , "    return;"
  , "}" ]

-- | A module with a comment of its own on each kind of element whose comment
-- reaches the C, each one a different text that names the element. The
-- interface reaches the section of the class that provides it, and its
-- procedure the pointer of the access port; the procedure of the class has a
-- comment of its own, so it inherits nothing that would print the text
-- twice. The elements whose comment does not reach the C yet are left without
-- one: the sink port of a handler and the statements (step 3f).
everyElement :: String
everyElement = unlines
  [ "/** Doc const. */"
  , "const limit : u32 = 9;"
  , ""
  , "/** Doc struct. */"
  , "struct Point {"
  , "    x : u32; /**< Doc struct field. */"
  , "};"
  , ""
  , "/** Doc enum. */"
  , "enum Mode {"
  , "    Off, /**< Doc variant. */"
  , "    On(u32) /**< Doc variant with data. */"
  , "};"
  , ""
  , "/** Doc interface. */"
  , "interface ICounter {"
  , "    /** Doc interface procedure. */"
  , "    procedure add(&mut self, by : u32);"
  , "};"
  , ""
  , "/** Doc resource class. */"
  , "resource class CCounter provides ICounter {"
  , "    count : u32; /**< Doc resource field. */"
  , ""
  , "    /** Doc procedure. */"
  , "    procedure add(&mut self, by : u32) {"
  , "        self->count = self->clamp(self->count + by);"
  , "        return;"
  , "    }"
  , ""
  , "    /** Doc method. */"
  , "    method clamp(&priv self, v : u32) -> u32 {"
  , "        var r : u32 = v;"
  , "        if (r > limit) {"
  , "            r = self->count;"
  , "        }"
  , "        return r;"
  , "    }"
  , "};"
  , ""
  , "/** Doc task class. */"
  , "task class CWorker {"
  , "    step : u32; /**< Doc task field. */"
  , "    counter : access ICounter; /**< Doc access port. */"
  , "    timer : sink TimeVal triggers tick; /**< Doc sink port. */"
  , ""
  , "    /** Doc viewer. */"
  , "    viewer doubled(&self, b : u32) -> u32 {"
  , "        return b + self->step;"
  , "    }"
  , ""
  , "    /** Doc action. */"
  , "    action tick(&priv self, _t : TimeVal) {"
  , "        self->counter.add(self->doubled(1));"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "/** Doc function. */"
  , "function twice(v : u32) -> u32 {"
  , "    return v + v;"
  , "}"
  , ""
  , "/** Doc extern function. */"
  , "extern function now() -> u32;" ]

-- | The texts of the comments of 'everyElement'.
everyComment :: [T.Text]
everyComment =
  [ "Doc const.", "Doc struct.", "Doc struct field.", "Doc enum.", "Doc variant."
  , "Doc variant with data.", "Doc resource class.", "Doc resource field.", "Doc procedure."
  , "Doc method.", "Doc viewer.", "Doc task class.", "Doc task field.", "Doc access port.", "Doc sink port."
  , "Doc action.", "Doc function.", "Doc extern function.", "Doc interface procedure.", "Doc interface." ]

-- | An interface that extends another one, both documented with their
-- procedures, a resource class that provides it with procedures without a
-- comment of their own and another name for a parameter, and a task class
-- that reaches it through an access port.
inheritedProcedure :: String
inheritedProcedure = unlines
  [ "enum BusError {"
  , "    NotStarted,"
  , "    Overrun"
  , "};"
  , ""
  , "/**"
  , " * Reset of a device."
  , " */"
  , "interface IBase {"
  , "    /**"
  , "     * Resets the device."
  , "     */"
  , "    procedure reset(&mut self);"
  , "};"
  , ""
  , "/**"
  , " * Transactions on a bus."
  , " */"
  , "interface IBus extends IBase {"
  , "    /**"
  , "     * Ends the transaction."
  , "     *"
  , "     * @param[out] status Error seen during the transaction, if any."
  , "     * @error NotStarted No transaction is in course."
  , "     * @error Overrun The receiver lost bytes."
  , "     */"
  , "    procedure end(&mut self, status : &mut Status<BusError>);"
  , "};"
  , ""
  , "/**"
  , " * Driver of the bus."
  , " */"
  , "resource class CDriver provides IBus {"
  , "    started : bool;"
  , ""
  , "    procedure end(&mut self, st : &mut Status<BusError>) {"
  , "        if (self->started) {"
  , "            *st = Success;"
  , "        } else {"
  , "            *st = Failure(BusError::NotStarted);"
  , "        }"
  , "        self->started = false;"
  , "        return;"
  , "    }"
  , ""
  , "    procedure reset(&mut self) {"
  , "        self->started = false;"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "/**"
  , " * Client of the bus."
  , " */"
  , "task class CClient {"
  , "    bus : access IBus;"
  , "    timer : sink TimeVal triggers tick;"
  , ""
  , "    action tick(&priv self, _t : TimeVal) {"
  , "        var st : Status<BusError> = Success;"
  , "        self->bus.end(&mut st);"
  , "        return;"
  , "    }"
  , "};" ]

spec :: Spec
spec = describe "Documentation comments in the C of a module" $ do
  it "give a procedure the comment of its interface, also an extended one, a class its interfaces and a pointer its summary" $
    fmap fst (renderDocumentedFiles "test" [("test", inheritedProcedure)]) `shouldBe` Right (T.unlines
      [ "#ifndef TEST_H__"
      , "#define TEST_H__"
      , ""
      , "#include <termina.h>"
      , ""
      , "typedef enum {"
      , "    BusError__NotStarted,"
      , "    BusError__Overrun"
      , "} termina__enum__BusError_t;"
      , ""
      , "typedef struct {"
      , "    termina__enum__BusError_t _variant;"
      , "} BusError;"
      , ""
      , "typedef struct {"
      , "    BusError _0;"
      , "} termina__enum__Status__BusError__Failure_params_t;"
      , ""
      , "typedef struct {"
      , "    termina__enum__Status__BusError__Failure_params_t Failure;"
      , "    termina__enum__Status_t _variant;"
      , "} Status__BusError;"
      , ""
      , "/**"
      , " * @brief Driver of the bus."
      , " *"
      , " * @par Provides"
      , " * - `IBus`: Transactions on a bus."
      , " * - `IBase`: Reset of a device."
      , " */"
      , "typedef struct {"
      , "    termina__resource_lock_type_t _lock_type;"
      , "    _Bool started;"
      , "} CDriver;"
      , ""
      , "/**"
      , " * @brief Ends the transaction."
      , " *"
      , " * @param[in] termina__ev Event that started the current activation. It carries"
      , " *                        the task or handler that processes it, on whose behalf"
      , " *                        resources are locked."
      , " * @param[in,out] termina__this Instance of `CDriver` on which the procedure"
      , " *                              runs."
      , " * @param[out] st Error seen during the transaction, if any."
      , " *"
      , " * @par Errors"
      , " * - `NotStarted`: No transaction is in course."
      , " * - `Overrun`: The receiver lost bytes."
      , " */"
      , "void CDriver__end(const termina__event_t * const termina__ev,"
      , "                  void * const termina__this, Status__BusError * const st);"
      , ""
      , "/**"
      , " * @brief Resets the device."
      , " *"
      , " * @param[in] termina__ev Event that started the current activation. It carries"
      , " *                        the task or handler that processes it, on whose behalf"
      , " *                        resources are locked."
      , " * @param[in,out] termina__this Instance of `CDriver` on which the procedure"
      , " *                              runs."
      , " */"
      , "void CDriver__reset(const termina__event_t * const termina__ev,"
      , "                    void * const termina__this);"
      , ""
      , "#define CClient__timer 0"
      , ""
      , "/**"
      , " * @brief Client of the bus."
      , " */"
      , "typedef struct {"
      , "    termina__id_t _task_id;"
      , "    termina__id_t _task_msg_queue_id;"
      , "    termina__id_t timer;"
      , "    struct {"
      , "        void * _that;"
      , "        void (* end)(const termina__event_t * const termina__ev,"
      , "                     void * const termina__this,"
      , "                     Status__BusError * const status); /**< Ends the transaction. */"
      , "    } bus;"
      , "} CClient;"
      , ""
      , "void termina__task_entry__CClient(void * const arg);"
      , ""
      , "void CClient__tick(const termina__event_t * const termina__ev,"
      , "                   void * const termina__this,"
      , "                   const TimeVal termina__ignored__t);"
      , ""
      , "#endif" ])
  it "reach the C once for every kind of element that has a C declaration" $
    case renderDocumentedFiles "test" [("test", everyElement)] of
      Left err -> expectationFailure (T.unpack err)
      Right (header, source) ->
        [ (c, n) | c <- everyComment, let n = T.count c (header <> source), n /= 1 ] `shouldBe` []
  it "document a struct, its fields, a function and its parameters in the header" $
    fmap fst (renderDocumentedFiles "test" [("test", pointAndDistance)]) `shouldBe` Right (T.unlines
      [ "#ifndef TEST_H__"
      , "#define TEST_H__"
      , ""
      , "#include <termina.h>"
      , ""
      , "/**"
      , " * @brief A point of the screen."
      , " */"
      , "typedef struct {"
      , "    uint32_t x; /**< Abscissa, in pixels. */"
      , "    uint32_t y; /**< Ordinate, in pixels. */"
      , "} Point;"
      , ""
      , "/**"
      , " * @brief Distance between two points along the axes."
      , " *"
      , " * @param[in] a First point."
      , " * @param[in] b Second point."
      , " * @param[out] d The distance, in pixels."
      , " */"
      , "void manhattan(const Point a, const Point b, uint32_t * const d);"
      , ""
      , "#endif" ])
