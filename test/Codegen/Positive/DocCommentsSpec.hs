-- | A deployment with an instance of every kind that has facts: a periodic
-- timer and an interrupt, a handler and two tasks, a channel between them, a
-- pool and a resource that the handler and a task share, which reaches
-- another resource through an access port.
deployment :: String
deployment = unlines
  [ "interface ITrace {"
  , "    procedure mark(&mut self);"
  , "};"
  , ""
  , "resource class CTrace provides ITrace {"
  , "    marks : u32;"
  , ""
  , "    procedure mark(&mut self) {"
  , "        self->marks = self->marks + 1;"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "interface ICounter {"
  , "    procedure add(&mut self, by : u32);"
  , "};"
  , ""
  , "resource class CCounter provides ICounter {"
  , "    count : u32;"
  , "    log : access ITrace;"
  , ""
  , "    procedure add(&mut self, by : u32) {"
  , "        self->count = self->count + by;"
  , "        self->log.mark();"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "handler class CIrq {"
  , "    irq : sink TimeVal triggers fired;"
  , "    counter : access ICounter;"
  , ""
  , "    action fired(&priv self, _t : TimeVal) {"
  , "        self->counter.add(1);"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "task class CProducer {"
  , "    timer : sink TimeVal triggers tick;"
  , "    counter : access ICounter;"
  , "    samples : access Allocator<u32>;"
  , "    output : out box u32;"
  , ""
  , "    action tick(&priv self, _t : TimeVal) {"
  , "        self->counter.add(1);"
  , "        var opt : Option<box u32> = None;"
  , "        self->samples.alloc(&mut opt);"
  , "        match opt {"
  , "            case Some(b) => {"
  , "                self->output.send(b);"
  , "            }"
  , "            case None => {"
  , "            }"
  , "        }"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "task class CConsumer {"
  , "    input : in box u32 triggers take;"
  , "    samples : access Allocator<u32>;"
  , ""
  , "    action take(&priv self, b : box u32) {"
  , "        self->samples.free(b);"
  , "        return;"
  , "    }"
  , "};"
  , ""
  , "emitter timer : PeriodicTimer = { period = { tv_sec = 1, tv_usec = 500000 } };"
  , "emitter fast : PeriodicTimer = { period = { tv_sec = 0, tv_usec = 10000 } };"
  , "resource trace : CTrace = { marks = 0 };"
  , "resource counter : CCounter = { count = 0, log <-> trace };"
  , "resource samples : Pool<u32; 8>;"
  , "channel queue : MsgQueue<box u32; 4>;"
  , "handler irq_handler : CIrq = { irq <- fast, counter <-> counter };"
  , "#[priority(10)]"
  , "task producer : CProducer = { timer <- timer, counter <-> counter, samples <-> samples, output -> queue };"
  , "#[priority(20)]"
  , "#[stack_size(8192)]"
  , "task consumer : CConsumer = { input <- queue, samples <-> samples };" ]

