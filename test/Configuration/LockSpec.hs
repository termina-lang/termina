{-# LANGUAGE OverloadedStrings #-}

-- | The lock of a project: its identity of packages, its format and its file.
module Configuration.LockSpec (spec) where

import Configuration.Lock

import qualified Data.ByteString.Char8 as BS
import qualified Data.Text as T
import Data.Yaml (decodeEither')
import System.Directory
import System.FilePath
import Test.Hspec

commit :: String
commit = "a1b2c3d4e5f6789012345678901234567890abcd"

hash :: String
hash = "sha256:" ++ replicate 64 'f'

package :: String -> String -> String -> String -> String
package url rev c h = "  - git: " ++ url ++ "\n    rev: " ++ rev ++ "\n    resolved-rev: " ++ c ++ "\n    content-hash: " ++ h ++ "\n"

lockText :: [String] -> String
lockText pkgs = "version: 1\npackages:\n" ++ concat pkgs

parse :: String -> Either String Lock
parse yaml = either (Left . show) parseLock (decodeEither' (BS.pack yaml))

locked :: String -> String -> LockedPackage
locked url rev = LockedPackage (T.pack url) (T.pack rev) (T.pack commit) (T.pack hash)

spec :: Spec
spec = do

  describe "identity of a package" $ do

    it "drops the scheme, a trailing .git and a trailing slash" $
      map normalizeUrl ["https://github.com/termina-lang/pus-services", "https://github.com/termina-lang/pus-services.git",
        "https://github.com/termina-lang/pus-services/", "https://github.com/termina-lang/pus-services.git/"]
        `shouldBe` replicate 4 "github.com/termina-lang/pus-services"

    it "puts the path in lowercase only on hosts that ignore its case" $
      map normalizeUrl ["https://GitHub.com/Termina-Lang/PUS-Services.git", "https://gitlab.com/Termina/Drivers",
        "https://Git.UAH.es/Termina/Drivers.git"]
        `shouldBe` ["github.com/termina-lang/pus-services", "gitlab.com/termina/drivers", "git.uah.es/Termina/Drivers"]

  describe "parsing" $ do

    it "reads the packages of a lock" $
      parse (lockText [package "https://github.com/termina-lang/pus-services" "v0.3.1" commit hash])
        `shouldBe` Right (Lock 1 [locked "https://github.com/termina-lang/pus-services" "v0.3.1"])

    it "reads a lock without packages" $
      parse "version: 1\n" `shouldBe` Right (Lock 1 [])

    it "rejects a version it does not know before anything else" $
      parse "version: 2\nunknown: 3\n"
        `shouldBe` Left "termina.lock version 2 is not supported by this version of termina (supported: 1)"

    it "rejects an unknown field" $
      either (const True) (const False) (parse (lockText [package "https://github.com/a/b" "v1" commit hash ++ "    branch: main\n"]))
        `shouldBe` True

    it "rejects a URL that is not https://, a short SHA and a hash that is not sha256" $
      map (either (const True) (const False) . parse . lockText) [
          [package "git@github.com:a/b" "v1" commit hash],
          [package "https://github.com/a/b" "v1" "a1b2c3d" hash],
          [package "https://github.com/a/b" "v1" (map succ' commit) hash],
          [package "https://github.com/a/b" "v1" commit ("md5:" ++ replicate 32 'f')]
        ] `shouldBe` replicate 4 True

    it "rejects a package that appears twice, written in two ways" $
      parse (lockText [package "https://github.com/a/b" "v1" commit hash, package "https://github.com/A/B.git" "v2" commit hash])
        `shouldBe` Left "the package github.com/a/b appears twice in termina.lock"

  describe "rendering" $ do

    it "writes the packages in the order of their identity, and reads them back" $ do
      let lock = Lock 1 [locked "https://github.com/termina-lang/pus-services" "v0.3.1", locked "https://github.com/termina-lang/embedded-hal" "1.0"]
          text = renderLock lock
      lines text `shouldBe` [
          "# termina.lock: generated by termina, do not edit. Commit it with vendor/.",
          "version: 1",
          "packages:",
          "  - git: https://github.com/termina-lang/embedded-hal",
          "    rev: \"1.0\"",
          "    resolved-rev: " ++ commit,
          "    content-hash: " ++ hash,
          "  - git: https://github.com/termina-lang/pus-services",
          "    rev: \"v0.3.1\"",
          "    resolved-rev: " ++ commit,
          "    content-hash: " ++ hash
        ]
      fmap lockPackages (parse text) `shouldBe` Right (reverse (lockPackages lock))

  describe "file" $

    it "reads a missing lock as empty, and removes the file when the lock has no packages" $ do
      tmp <- getTemporaryDirectory
      let root = tmp </> "termina-lock-spec"
          path = root </> "termina.lock"
      removePathForcibly root
      createDirectoryIfMissing True root
      decodeLockFile path `shouldReturn` Right emptyLock
      writeLockFile path (Lock 1 [locked "https://github.com/a/b" "v1"])
      decodeLockFile path `shouldReturn` Right (Lock 1 [locked "https://github.com/a/b" "v1"])
      writeLockFile path emptyLock
      doesFileExist path `shouldReturn` False

  where

    succ' c = if c == 'a' then 'A' else c
