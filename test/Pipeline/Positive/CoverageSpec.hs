-- | Full-pipeline goldens of the instrumented C and the map of the coverage.
module Pipeline.Positive.CoverageSpec (spec) where

import Pipeline.Common
import Golden

import Test.Hspec

-- | One function per construct that the coverage instruments.
coverageModule :: String
coverageModule = unlines
    [ "enum Mode {"
    , "    Off,"
    , "    Low,"
    , "    High"
    , "};"
    , ""
    , "function check(v : u32) -> bool {"
    , "    return v > 10;"
    , "}"
    , ""
    , "function if_no_else(x : u32) -> u32 {"
    , "    var y : u32 = x;"
    , "    if (x > 3) {"
    , "        y = y + 1;"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function if_chain(x : u32) -> u32 {"
    , "    var y : u32;"
    , "    if (x < 3) {"
    , "        y = 1;"
    , "    } else if (x < 7) {"
    , "        y = 2;"
    , "    } else {"
    , "        y = 3;"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function for_plain(n : u32) -> u32 {"
    , "    var acc : u32 = 0;"
    , "    for i : u32 in 0 .. 8 {"
    , "        acc = acc + i;"
    , "    }"
    , "    return acc + n;"
    , "}"
    , ""
    , "function for_while(limit : u32) -> u32 {"
    , "    var acc : u32 = 0;"
    , "    for i : u32 in 0 .. 8 while (acc < limit) {"
    , "        acc = acc + i;"
    , "    }"
    , "    return acc;"
    , "}"
    , ""
    , "function match_no_default(m : Mode) -> u32 {"
    , "    var y : u32;"
    , "    match m {"
    , "        case Off => {"
    , "            y = 1;"
    , "        }"
    , "        case Low => {"
    , "            y = 2;"
    , "        }"
    , "        case High => {"
    , "            y = 3;"
    , "        }"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function match_default(m : Mode) -> u32 {"
    , "    var y : u32;"
    , "    match m {"
    , "        case High => {"
    , "            y = 3;"
    , "        }"
    , "        case _ => {"
    , "            y = 9;"
    , "        }"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function cond_and(a : u32, b : u32) -> u32 {"
    , "    var y : u32;"
    , "    if (a > 1 && b > 2) {"
    , "        y = 1;"
    , "    } else {"
    , "        y = 2;"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function elif_or(a : u32, b : u32) -> u32 {"
    , "    var y : u32;"
    , "    if (a == 0) {"
    , "        y = 1;"
    , "    } else if (a > 5 || b > 5) {"
    , "        y = 2;"
    , "    } else {"
    , "        y = 3;"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "function value_and(a : u32, b : u32) -> bool {"
    , "    var both : bool = a > 1 && b > 2;"
    , "    return both;"
    , "}"
    , ""
    , "function arg_or(a : u32, b : u32) -> bool {"
    , "    return check(a) || b == 0;"
    , "}"
    , ""
    , "function pick(c : bool, v : u32) -> u32 {"
    , "    var r : u32;"
    , "    if (c) {"
    , "        r = v;"
    , "    } else {"
    , "        r = 0;"
    , "    }"
    , "    return r;"
    , "}"
    , ""
    , "function call_with_and(a : u32, b : u32) -> u32 {"
    , "    var r : u32 = pick(a > 1 && b > 2, a);"
    , "    return r;"
    , "}"
    , ""
    , "function index_check(buf : &[u32; 4], i : usize) -> u32 {"
    , "    var x : u32 = buf[i];"
    , "    var y : u32 = x + 1;"
    , "    return y;"
    , "}"
    , ""
    , "function negated_and(a : u32, b : u32) -> u32 {"
    , "    var y : u32 = 0;"
    , "    if ((a > 1 && b > 2) == false) {"
    , "        y = 1;"
    , "    }"
    , "    return y;"
    , "}"
    , ""
    , "enum Single {"
    , "    Only"
    , "};"
    , ""
    , "function match_sole(s : Single) -> u32 {"
    , "    var y : u32 = 0;"
    , "    match s {"
    , "        case Only => {"
    , "            y = y + 1;"
    , "        }"
    , "    }"
    , "    return y;"
    , "}"
    ]

spec :: Spec
spec = describe "Full pipeline: coverage" $ do
  let (cSource, coverageMap) = runCoverageBuild "test" [("test", coverageModule)]
  it "instruments each statement, decision and condition" $
    goldenC "coverage_samples" cSource
  it "writes the map of the flags" $
    goldenJSON "coverage_samples" coverageMap
